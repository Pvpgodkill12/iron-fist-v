import type { CharacterData, MoveData } from './types';

function mv(
  id: string,
  name: string,
  opts: Omit<MoveData, 'id' | 'name' | 'height'> & { height?: MoveData['height'] },
): MoveData {
  return {
    id,
    name,
    height: opts.height ?? 'mid',
    ...opts,
  };
}

function makeThrow(id: string, name: string, damage: number, startup = 12): MoveData {
  return mv(id, name, {
    height: 'high',
    startup,
    active: 3,
    recovery: 28,
    damage,
    reach: 1.38,
    hitstun: 0,
    blockstun: 0,
    pushback: 0,
    anim: 'throw_suplex',
    limb: 'both',
    isThrow: true,
  });
}

